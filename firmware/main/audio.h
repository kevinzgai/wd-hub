// 提示音模块 —— 用 I2S 直驱功放播四段状态提示音。
//
// 硬件结论（已实测确认，见 .workbuddy/memory/2026-10-26.md）
// ------------------------------------------------------------
// 本机是 xingzhi-cube-1.54tft-wifi，上游用 NoAudioCodecSimplex：
// **没有 codec 芯片**，I2S 直接进功放芯片，所以不需要 I2C 初始化、
// 也不需要功放使能脚。
//   实测确认的引脚：BCLK=GPIO15  LRCK=GPIO16  DOUT=GPIO7
//   探测方法：写独立固件直接发正弦扫频音，用"能否听到"当探针
//   （没有示波器，声音本身就是通路证明，比查文档可靠）
//
// 为什么是采样而不是实时合成
// --------------------------
// 最初这里实时合成波形（零 Flash 占用、音高可代码调）。技术上做到了
// 和弦 + 非谐泛音 + 指数衰减，但听感始终是"电子音"。量化后找到根因：
// 合成器的音色是恒定的（泛音/基频比从 20ms 到 260ms 几乎不变），
// 而真实乐器会从亮变暗 38 倍。这是合成器的定义性特征，调参数补不上。
//
// 所以改成离线渲染好的 PCM 表，固件只负责展开成立体声后写 I2S。
// 四段共 36KB Flash（16MB 里可忽略），换来的是真人录制的音色。
// 代价是改音高/节奏要重跑 tools/gen_tones.py，不能运行时调 —— 可接受，
// 因为提示音定稿后基本不动。
//
// 线程模型
// --------
// audio_play() 只往队列里塞一个事件，立刻返回（非阻塞）。
// 真正的 I2S 写入在独立的 audio 任务里做，所以**绝不会**卡住
// LVGL 刷屏或 HTTP 轮询。这点很重要：一段提示音 200~300ms，
// 如果在 LVGL 任务里同步播，会掉十几帧。
#pragma once

#include <stdint.h>

// 播放事件。数值用于入队，不要随意改已有项的值。
//
// 四段靠"音高 + 音数 + 走向"区分，因为音色同源（同一段铃声拆出来的），
// 只能靠这几个维度区分语义：
//   DONE        叮→咚  下行双音，唯一的两音结构 → 完成、落地
//   ATTENTION   叮 叮  同音重复 → 未完成感，在等你推进
//   CONNECTED   叮     单声偏高 → 设备自报状态
//   SESSION_END 咚     单声偏低 → 告一段落
typedef enum {
    AUDIO_EV_NONE = 0,
    AUDIO_EV_DONE,        // 完成一项 todo：叮→咚，下行双音
    AUDIO_EV_ATTENTION,   // 等你操作：同音重复两次
    AUDIO_EV_CONNECTED,   // 首次连上服务端：单声短高音
    AUDIO_EV_SESSION_END, // 会话收工（working -1）：单声低音
} audio_event_t;

// 初始化 I2S 与播放任务。必须在 app_main 里调一次。
// 失败只会打日志，不会 abort —— 没声音不应该让整个看板起不来。
void audio_init(void);

// 投递一个播放事件。非阻塞，队列满时直接丢弃（宁可少响一次，
// 也不要在这里阻塞调用方）。
void audio_play(audio_event_t ev);

// 音量百分比 0..100，默认 AUDIO_VOLUME_DEFAULT。
// 提示音固定音量，不占用按键（VOL_UP/DOWN 目前是调亮度的）。
void audio_set_volume(int percent);
