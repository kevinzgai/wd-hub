#!/usr/bin/env python3
"""Generate short, harmonic UI tones as flash-resident PCM, with optional WAVs."""
import argparse
import json
import math
from pathlib import Path
import struct
import wave

RATE = 16000
TONES = (
    ("Nav", 1174.66, 38, 19200),
    ("Confirm", 1567.98, 48, 20000),
    ("Back", 987.77, 42, 19200),
)
TARGET = Path(__file__).resolve().parents[1] / "main" / "ui_sfx_pcm.inc"


def render(frequency, ms, amplitude):
    count = RATE * ms // 1000
    result = []
    for index in range(count):
        seconds = index / RATE
        attack = min(index / (RATE * .0015), 1)
        release = min((count - 1 - index) / (RATE * .008), 1)
        envelope = (.5 - .5 * math.cos(math.pi * attack))
        envelope *= (.5 - .5 * math.cos(math.pi * release))
        envelope *= math.exp(-seconds / .022)
        phase = 2 * math.pi * frequency * seconds
        # Only a faint octave above a stable fundamental; no noise or chirp.
        tone = (math.sin(phase) + .10 * math.sin(2 * phase)) / 1.10
        result.append(round(amplitude * envelope * tone))
    return result


def source(tones):
    lines = ["// Generated by tools/generate_ui_sfx.py; signed PCM16 at 16000 Hz.",
             "// Keep in read-only flash: the ESP32-C3 need not synthesize while feeding I2S."]
    for name, samples in tones.items():
        lines.append("static const int16_t k" + name + "[] = {")
        for offset in range(0, len(samples), 12):
            lines.append("    " + ", ".join(map(str, samples[offset:offset + 12])) + ",")
        lines.append("};")
    return "\n".join(lines) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--preview-dir", type=Path)
    args = parser.parse_args()
    tones = {name: render(hz, ms, amplitude) for name, hz, ms, amplitude in TONES}
    generated = source(tones)
    if args.check:
        assert TARGET.read_text(encoding="ascii") == generated, "Regenerate UI PCM"
    else:
        TARGET.write_text(generated, encoding="ascii", newline="\n")
    if args.preview_dir:
        args.preview_dir.mkdir(parents=True, exist_ok=True)
        sequence = [0] * 1600
        metrics = {}
        for name, samples in tones.items():
            sequence.extend(samples + [0] * 6400)
            rms = math.sqrt(sum(v * v for v in samples) / len(samples))
            metrics[name] = dict(ms=len(samples) * 1000 / RATE,
                                 peak=max(map(abs, samples)),
                                 rms_dbfs=20 * math.log10(rms / 32768))
        with wave.open(str(args.preview_dir / "key-sounds.wav"), "wb") as wav:
            wav.setparams((1, 2, RATE, 0, "NONE", "not compressed"))
            wav.writeframes(struct.pack("<" + "h" * len(sequence), *sequence))
        (args.preview_dir / "tone-analysis.json").write_text(
            json.dumps(metrics, indent=2) + "\n", encoding="ascii")
        print(json.dumps(metrics))


if __name__ == "__main__":
    main()
